"""Build the organizer's flat ZIP: root Python files and requirements.txt only."""

from __future__ import annotations

import argparse
from collections.abc import Callable
import os
from pathlib import Path
import stat
import sys
import tempfile
import zipfile


ROOT = Path(__file__).resolve().parent
MAX_ARCHIVE_BYTES = 100_000_000
REQUIRED_FILES = (
    "solution.py",
    "validation.py",
    "offline_baseline.py",
    "requirements.platform.txt",
    "agent/__init__.py",
)

# The platform copies only root .py files. Keep real source filenames for
# tracebacks/inspect, and install only the package names present in this build.
# This loader never materializes or overwrites directories in the task data.
_FLAT_LOADER = '''

# Generated by build_submission.py for the organizer's root-only copy step.
import importlib.abc as _alfa_flat_abc
import importlib.machinery as _alfa_flat_machinery
import importlib.util as _alfa_flat_util
from pathlib import Path as _AlfaFlatPath
import sys as _alfa_flat_sys

_alfa_flat_root = _AlfaFlatPath(__file__).resolve().parent
_alfa_flat_manifest = __MANIFEST__
__path__ = []
__package__ = __name__
__spec__.submodule_search_locations = __path__


class _AlfaFlatFinder(_alfa_flat_abc.MetaPathFinder):
    def find_spec(self, fullname, path=None, target=None):
        entry = _alfa_flat_manifest.get(fullname)
        if entry is None:
            return None
        filename, package = entry
        if filename is None:
            # Namespace packages also work when a source subdirectory has no
            # __init__.py. Their children still come only from this manifest.
            return _alfa_flat_machinery.ModuleSpec(fullname, loader=None, is_package=True)
        source = _alfa_flat_root / filename
        if source.is_symlink() or not source.is_file():
            raise ImportError("Missing regular packaged source: " + filename)
        return _alfa_flat_util.spec_from_file_location(
            fullname, source, submodule_search_locations=[] if package else None,
        )


if "_alfa_flat_finder" not in globals():
    _alfa_flat_finder = _AlfaFlatFinder()
    _alfa_flat_sys.meta_path.insert(0, _alfa_flat_finder)
'''


def _is_link(path: Path) -> bool:
    return path.is_symlink() or (hasattr(path, "is_junction") and path.is_junction())


def source_files() -> list[Path]:
    """Return regular allowlisted source files, retaining the repository layout."""
    files = {ROOT / name for name in REQUIRED_FILES}
    agent_dir = ROOT / "agent"
    if _is_link(agent_dir) or not agent_dir.is_dir():
        raise ValueError("agent must be a regular directory inside the project.")
    for directory, directories, filenames in os.walk(agent_dir, followlinks=False):
        parent = Path(directory)
        directories[:] = [name for name in directories if name != "__pycache__"]
        for name in directories:
            if _is_link(parent / name):
                raise ValueError(f"Linked source directory: {(parent / name).relative_to(ROOT)}")
        files.update(parent / name for name in filenames if name.endswith(".py"))
    for path in files:
        if _is_link(path) or not path.is_file():
            raise ValueError(f"Missing regular source file: {path.relative_to(ROOT)}")
        if not path.resolve().is_relative_to(ROOT.resolve()):
            raise ValueError(f"Source file is outside the project: {path.relative_to(ROOT)}")
    return sorted(files, key=lambda path: path.relative_to(ROOT).as_posix())


def _read_source(path: Path) -> bytes:
    """Read an ordinary file without following a final-component symlink."""
    descriptor = os.open(path, os.O_RDONLY | getattr(os, "O_BINARY", 0) | getattr(os, "O_NOFOLLOW", 0))
    with os.fdopen(descriptor, "rb") as stream:
        before = os.fstat(stream.fileno())
        if not stat.S_ISREG(before.st_mode):
            raise ValueError(f"Source must be a regular file: {path}")
        content = stream.read()
        after = os.fstat(stream.fileno())
        if (before.st_size, before.st_mtime_ns) != (after.st_size, after.st_mtime_ns):
            raise ValueError(f"Source changed while archiving: {path}")
        return content


def archive_files(*, read_bytes: Callable[[Path], bytes] | None = None) -> dict[str, bytes]:
    """Return the flat deliverable, shared by the CLI and bounded app export.

    ``read_bytes`` allows the app to retain its stricter cumulative read limits.
    The source package remains unchanged; only the ZIP layout is transformed.
    """
    reader = read_bytes or _read_source
    sources = source_files()
    files: dict[str, bytes] = {}
    manifest: dict[str, tuple[str | None, bool]] = {}
    seen_names: set[str] = set()
    init_source = None
    for path in sources:
        relative = path.relative_to(ROOT)
        if relative.parts[0] != "agent":
            name = "requirements.txt" if relative.name == "requirements.platform.txt" else relative.name
        elif relative.as_posix() == "agent/__init__.py":
            name = "agent.py"
        else:
            parts = relative.with_suffix("").parts
            if not all(part.isidentifier() for part in parts):
                raise ValueError(f"Invalid Python module path: {relative}")
            package = parts[-1] == "__init__"
            module_parts = parts[:-1] if package else parts
            module = ".".join(module_parts)
            if module in manifest and manifest[module][0] is not None:
                raise ValueError(f"Ambiguous packaged module: {module}")
            name = "_alfa_" + "__".join(parts) + ".py"
            manifest[module] = (name, package)
            for count in range(2, len(module_parts)):
                parent = ".".join(module_parts[:count])
                if parent in manifest and not manifest[parent][1]:
                    raise ValueError(f"Module also used as a package: {parent}")
                manifest.setdefault(parent, (None, True))
        if name.casefold() in seen_names:
            raise ValueError(f"Colliding flat archive filename: {name}")
        seen_names.add(name.casefold())
        content = reader(path)
        if name == "agent.py":
            init_source = content
        else:
            files[name] = content
    if init_source is None:
        raise ValueError("Missing agent package initializer.")
    # UTF-8 is the project's source encoding; utf-8-sig also accepts a BOM.
    initializer = init_source.decode("utf-8-sig")
    files["agent.py"] = (initializer + "\n" + _FLAT_LOADER.replace(
        "__MANIFEST__", repr(dict(sorted(manifest.items()))),
    )).encode("utf-8")
    return dict(sorted(files.items()))


def build_archive(output: Path) -> list[str]:
    sources = source_files()
    output = output.expanduser().absolute()
    protected = {*sources, ROOT / "requirements.txt", ROOT / "build_submission.py"}
    if output.resolve() in {path.resolve() for path in protected}:
        raise ValueError("The output path must not overwrite a source file.")
    files = archive_files()
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        prefix=f".{output.name}.", suffix=".tmp", dir=output.parent, delete=False,
    ) as stream:
        temporary = Path(stream.name)
    try:
        names = list(files)
        with zipfile.ZipFile(temporary, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
            for name, content in files.items():
                archive.writestr(name, content)
        if temporary.stat().st_size > MAX_ARCHIVE_BYTES:
            raise ValueError("Submission ZIP exceeds the organizer's 100 MB limit.")
        with zipfile.ZipFile(temporary) as archive:
            damaged = archive.testzip()
            if damaged is not None:
                raise ValueError(f"Archive verification failed: {damaged}")
            if archive.namelist() != names:
                raise ValueError("Archive contents do not match the selected source files.")
            for required in ("solution.py", "agent.py", "requirements.txt"):
                archive.getinfo(required)
        os.replace(temporary, output)
    finally:
        temporary.unlink(missing_ok=True)
    return names


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "delivery" / "solution.zip")
    args = parser.parse_args()
    try:
        names = build_archive(args.output)
        print("Included files:")
        for name in names:
            print(f"  {name}")
        output = args.output.expanduser().absolute()
        print(f"Archive size: {output.stat().st_size} bytes")
        print(f"Saved: {output}")
        return 0
    except (OSError, ValueError, KeyError, zipfile.BadZipFile) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
